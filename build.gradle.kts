// The SDK's version reaches the User-Agent through a generated constant, so
// gradle.properties stays the only place it is written down.
val generateSdkVersion =
    tasks.register("generateSdkVersion") {
      val sdkVersion = project.version.toString()
      val outputDir = layout.buildDirectory.dir("generated/sources/sdk-version/java/main")
      inputs.property("version", sdkVersion)
      outputs.dir(outputDir)
      doLast {
        val file = outputDir.get().file("com/teachmehipaa/core/SdkVersion.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package com.teachmehipaa.core;

            /** Generated by Gradle from gradle.properties. */
            final class SdkVersion {
              static final String VERSION = "$sdkVersion";

              private SdkVersion() {}
            }
            """
                .trimIndent() + "\n"
        )
      }
    }

sourceSets {
  main { java.srcDir(generateSdkVersion) }
