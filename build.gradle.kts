// The second lock on a release, after the workflow's `publish` input: gradle.properties commits
// publishGuard=locked, and every publish to a remote repository fails until a reviewed change sets
// it to `unlocked` (CONTRIBUTING.md). publishToMavenLocal is never guarded.
val checkPublishGuard =
    tasks.register("checkPublishGuard") {
      group = "publishing"
      description =
          "Fails unless publishGuard=unlocked, the version is a release and a key signs it."
      val guard = providers.gradleProperty("publishGuard").orElse("locked")
      val releaseVersion = project.version.toString()
      val signed = signingKey.isPresent
      doLast {
        if (guard.get() != "unlocked") {
          throw GradleException(
              "Publishing is locked: gradle.properties has publishGuard=${guard.get()}. Set it" +
                  " to unlocked in a reviewed release PR (see CONTRIBUTING.md)."
          )
        }
        if (releaseVersion.endsWith("-SNAPSHOT")) {
          throw GradleException("Maven Central takes releases only; version is $releaseVersion")
        }
        if (!signed) {
          throw GradleException("Maven Central needs signed artifacts; set signingInMemoryKey")
        }
      }
    }

tasks.withType<PublishToMavenRepository>().configureEach { dependsOn(checkPublishGuard) }
